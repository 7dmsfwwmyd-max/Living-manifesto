import {rm,writeFile,readFile,readdir} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
await rm('dist',{recursive:true,force:true});
execFileSync(process.execPath,['deploy.mjs'],{stdio:'inherit'});
execFileSync(process.execPath,['automatic-analysis-patch.mjs'],{stdio:'inherit'});
execFileSync(process.execPath,['topic-discovery-patch.mjs'],{stdio:'inherit'});
execFileSync(process.execPath,['learning-studio-patch.mjs'],{stdio:'inherit'});
execFileSync(process.execPath,['learning-sync-patch.mjs'],{stdio:'inherit'});
execFileSync(process.execPath,['evergreen-patch.mjs'],{stdio:'inherit'});
const commit=process.env.GITHUB_SHA||execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim();
let worker=await readFile('dist/_worker.js','utf8');worker=worker.replace("version:'0.5.6'","version:'0.5.6',commit:"+JSON.stringify(commit));await writeFile('dist/_worker.js',worker);
for(const file of ['_worker.js','app.js','service-worker.js'])execFileSync(process.execPath,['--check','dist/'+file],{stdio:'inherit'});
execFileSync(process.execPath,['verify-release.mjs'],{stdio:'inherit'});
execFileSync(process.execPath,['--test','tests/generated.test.mjs'],{stdio:'inherit'});
const release={version:'0.5.6',commit,files:{}};
await writeFile('dist/.assetsignore','_worker.js\n');
let sw=await readFile('dist/service-worker.js','utf8');sw=sw.replace(/lm-private-shell-[^']+/,'lm-private-shell-056-'+commit.slice(0,12));await writeFile('dist/service-worker.js',sw);
for(const name of (await readdir('dist')).sort())release.files[name]=createHash('sha256').update(await readFile('dist/'+name)).digest('hex');
await writeFile('dist/release.json',JSON.stringify(release,null,2)+'\n');
console.log('Built and tested v'+release.version+' at '+commit);
